#!/usr/bin/env python3
"""scripts/conformance-report.py: writes docs/benchmarks/results/conformance/README.md from a conformance run directory.
Every number is read from the run's files (summary.json, per-set install.json and restore.json, provenance.json); the prose states only
what they support. Re-run after another run lands.

Usage: python3 scripts/conformance-report.py [run dir]   (default docs/benchmarks/results/conformance/run-2026-10-20)
"""
import collections, glob, hashlib, json, math, os, sys


def _jload(path):
    with open(path) as fh:
        return json.load(fh)


def _jsonl(path):
    with open(path) as fh:
        return [json.loads(line) for line in fh]


def _write(path, text):
    with open(path, 'w') as fh:
        fh.write(text)


def _sha(path):
    with open(path, 'rb') as fh:
        return hashlib.sha256(fh.read()).hexdigest()

RUN = sys.argv[1] if len(sys.argv) > 1 else 'docs/benchmarks/results/conformance/run-2026-10-20'
OUT = os.path.join(os.path.dirname(RUN.rstrip('/')), 'README.md')
FLOW_NAMES = {
    'F1': 'F1 node-01 UDP to the Mac (in port 1)', 'F2': 'F2 rpi-hailo UDP to the Mac (in port 1; the quarantine candidate)',
    'F3': 'F3 node-01 ARP who-has (in port 1)', 'F4': 'F4 Mac UDP to node-01 (in port 2)', 'F5': 'F5 Mac UDP to rpi-hailo (in port 2; the quarantine candidate)',
}


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 1.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - h) / d, (c + h) / d)


def sha(path):
    return _sha(path)


def main():
    rows = _jload(f'{RUN}/summary.json')['ruleSets']
    prov = _jload(f'{RUN}/provenance.json')
    flows = [(r, f) for r in rows for f in r['flows'] if 'agrees' in f]
    n, agree = len(flows), sum(1 for _, f in flows if f['agrees'])
    lo, hi = wilson(agree, n)
    kinds = collections.OrderedDict((k, [r for r in rows if r['kind'] == k]) for k in ('reference', 'surviving-mutant', 'model-admissible'))

    def vec(r):
        return tuple((f['flow'][:2], tuple(f['predictedObservable'])) for f in r['flows'])
    ref = {r['intent']: vec(r) for r in kinds['reference']}
    differ = {k: [r for r in v if vec(r) != ref[r['intent']]] for k, v in kinds.items() if k != 'reference'}
    separators = collections.Counter()
    for r in rows:
        if r['kind'] == 'reference':
            continue
        for f, fv, rv in zip(r['flows'], vec(r), ref[r['intent']]):
            if fv != rv:
                separators[f['flow'][:2]] += 1
    blind = collections.Counter(r['id'].split(':')[0] + ' ' + r['id'].split(':')[1] for r in kinds['surviving-mutant'] if vec(r) == ref[r['intent']] and ':' in r['id'])
    installs = [_jload(p) for p in sorted(glob.glob(f'{RUN}/*/install.json'))]
    restores = [_jload(p) for p in sorted(glob.glob(f'{RUN}/*/restore.json'))]
    inst_ok = sum(1 for i in installs if i.get('ok') is True and i.get('extraEntries') == 0 and i.get('tableMissEntries') == 1)
    rest_ok = sum(1 for i in restores if i.get('ok') is True and i.get('extraEntries') == 0 and i.get('tableMissEntries') == 1)
    sizes = sorted({i['rulesRequested'] for i in installs})
    fp = fn = 0  # predicted absent but seen, predicted present but not seen
    for _, f in flows:
        pred, obs = set(f['predictedObservable']), set(f['observedPorts'])
        fp += len(obs - pred)
        fn += len(pred - obs)
    # per flow: counts when predicted present
    present = collections.defaultdict(list)
    for _, f in flows:
        k = f['flow'][:2]
        c = f['counts']
        if 3 in f['predictedObservable']:
            present[(k, 'O2')].append(c['O2'])
        if 2 in f['predictedObservable']:
            present[(k, 'O3')].append(c['O3'])
        if 1 in f['predictedObservable']:
            present[(k, 'listener')].append(c['listener'])
    bridge = {l.split(' ', 1)[0]: l.split(' ', 1)[1] for l in prov['bridgeRepo'] if ' ' in l}
    scripts = {s: sha(f'scripts/{s}') for s in ('conformance-run.ts', 'export-conformance-rulesets.ts', 'conformance-report.py') if os.path.exists(f'scripts/{s}')}

    L = []
    w = L.append
    w('# On-wire conformance run (RQ4), 2026-10-20')
    w('')
    w('Generated by `scripts/conformance-report.py` from the run directory `' + RUN.split('conformance/')[-1] + '/`. Every number below is read from its files. '
      'This is **physical capture** evidence from the real Zodiac FX (firmware 0.86 per the ledger; not re-read by this run), taken through the bridge\'s guarded '
      'experiment install path. It tests whether the verifier\'s own model of a rule set predicts where real packets go.')
    w('')
    w('## Result')
    w('')
    w(f'**{len(rows)} rule sets, {n} flow checks: {agree} agree with the model, {n - agree} disagree.** The 95% Wilson interval on the per-flow agreement rate is '
      f'{100 * lo:.1f}% to {100 * hi:.1f}% (all-agree results still leave an interval; it is a statement about these {n} checks, not a proof about the switch). '
      f'Predicted-absent but seen: {fp}. Predicted-present but not seen: {fn}. All {len(installs)} installs and {len(restores)} restores were verified by readback '
      f'({inst_ok} and {rest_ok} with exactly one table-miss entry and no leftover entries), across rule sets of {min(sizes)} to {max(sizes)} rules.')
    w('')
    w('| Kind of rule set | Sets | Flow checks | Agree |')
    w('| :--- | ---: | ---: | ---: |')
    for k, v in kinds.items():
        fl = [f for r in v for f in r['flows'] if 'agrees' in f]
        w(f'| {k} | {len(v)} | {len(fl)} | {sum(1 for f in fl if f["agrees"])} |')
    w('')
    w('## What was sent and where it was seen')
    w('')
    w('For each rule set the harness installed it (`POST /api/experiment/install`), sent five flows from real hosts, captured at two points on the Jetson, compared with the '
      'prediction of the verifier\'s own match function (`matchesPacket` over the rules, highest priority first, table-miss drops), and restored the isolation policy.')
    w('')
    w('- **O3** (`enx9c69d39ddcc0`): a mirror of the Zodiac P2 link, independent of the rules under test. A frame from the sender\'s NIC here means the switch sent it out of port 2.')
    w('- **O2** (`enx9c69d39dd0a6`): the Zodiac P3 link. It shows what the rules chose to copy to the tap, but a frame there is physical proof the switch sent it out of port 3.')
    w('- **Port 1** is seen only as a datagram arriving at a listener bound to the workload NIC of the destination node.')
    w('')
    w('| Flow | Observable ports | Counts when the model predicts the packet appears (datagrams sent: 5; ARP: the kernel\'s 3 requests) |')
    w('| :--- | :--- | :--- |')
    for k in ('F1', 'F2', 'F3', 'F4', 'F5'):
        parts = [f'{loc} {min(v)} to {max(v)} over {len(v)} checks' for (kk, loc), v in sorted(present.items()) if kk == k]
        obsp = {'F1': '2, 3', 'F2': '2, 3', 'F3': '2, 3', 'F4': '1, 3', 'F5': '1, 3'}[k]
        w(f'| {FLOW_NAMES[k]} | {obsp} | {"; ".join(parts) if parts else "never predicted to appear"} |')
    w('')
    w('## How much these flows can see')
    w('')
    w(f'Agreement means little for a rule set the flows cannot tell from its reference. {len({vec(r) for r in rows})} distinct prediction patterns occur across the {len(rows)} sets.')
    w('')
    w('| Kind | Sets whose prediction differs from their intent\'s reference on at least one flow | Sets indistinguishable from the reference by these five flows |')
    w('| :--- | ---: | ---: |')
    for k, v in kinds.items():
        if k == 'reference':
            continue
        w(f'| {k} | {len(differ[k])} of {len(v)} | {len(v) - len(differ[k])} |')
    w('')
    w('Flows that separate a survivor or model set from its reference (count of sets): ' + ', '.join(f'{k} {v}' for k, v in sorted(separators.items())) +
      '. **F4 and F5 never separate a survivor from its reference**: they only distinguish the references of different intents from each other.')
    w('')
    w('The survivor mutations the flows cannot see, by operator and rule: ' + '; '.join(f'{k} ({v})' for k, v in sorted(blind.items())) +
      '. Two kinds of reason, both visible in that list: a mutation on the tap-return rule (`p3-tap-return`) or the P2 ARP rule needs a packet entering from the tap or an ARP request from the '
      'router side, which this testbed cannot send (the O2 NIC cannot transmit by design: fail-closed egress); a priority raise on a rule that already wins for all five flows changes no outcome '
      'for these packets. For those sets, "agrees" only says the five flows behaved like the reference.')
    w('')
    w('## What this does not show')
    w('')
    w('- **Five flows**, UDP and ARP only, five datagrams each (ARP: the kernel\'s three requests). No TCP, no ICMP, no VLAN, no port 3 ingress, no multicast. Agreement on five flows is evidence against a '
      'disagreement on those flows, not a proof for the rule set.')
    w('- **One switch, one firmware (0.86 per the ledger), one run.** No repeats; ordering and timing effects are untested.')
    w('- **The flow set cannot see 29 of the 38 survivors** (above), so it neither supports nor refutes the "equivalent mutant or gap in the checks" question for them.')
    w('- **The readback cannot distinguish rules that differ only by MAC** (the flow-stats parser carries no MAC fields), so any MAC-only difference between a rule set and what the switch holds would be invisible to the install verdict; the wire flows are the check there, and none of these sets match on MACs.')
    w('- **Port 1 egress is seen at the destination host, not on a wire tap**: the F4 and F5 listener counts were below the datagrams sent in some checks (the first packets wait while the lab router resolves the workload address); the check is "at least one arrived".')
    w('- **Admissible is the verifier\'s verdict over modelled fields.** This run tests that model against hardware; it does not make an admissible set correct for its intent.')
    w('- **Not tested here** (see also the 2026-10-16 "Still unmeasured" note in `.agents/network-context.md`, which this does not resolve): the switch-side hard timeout of an experimental rule (the case where the bridge dies mid-experiment). The bridge-side time limit and explicit restore were exercised on every set.')
    w('')
    w('## Provenance')
    w('')
    w(f'- Evidence: `physical_capture`; raw tcpdump text for both taps and the HTTP install and restore reports are in each rule set\'s directory, with `evidence-sha256.json` hashes. Rule sets under test: `rulesets/` (`index.json`).')
    w(f'- Bridge: commit `{bridge.get("commit", "?")}` on `{bridge.get("branch", "?")}`, {bridge.get("dirty_files", "?")} uncommitted files, `dist/sdn/zodiac-bridge-server.js` sha256 `{bridge.get("dist_sha256", "?")[:16]}`, {bridge.get("tcpdump", "")}, kernel {bridge.get("kernel", "")}; the bridge process was started by hand with the unit\'s command line and environment (the systemd unit is inactive).')
    w(f'- Hosts: node-01 `eth0` {prov["hosts"]["macs"].get("agentic-node-01")} (10.0.2.50); rpi-hailo `eth0` {prov["hosts"]["macs"].get("rpi-hailo")} (10.0.2.51); the Mac {prov["hosts"]["macIp"]} ({prov["hosts"]["macMac"]}). Started {prov["startedAtEt"]}.')
    # The run used the scripts as they were then; later edits change the current hashes, so the run-time ones are pinned here (taken from the first generated README).
    at_run = {'conformance-run.ts': '0da938c618ee817d', 'export-conformance-rulesets.ts': 'fd1aa170af18a99d', 'conformance-report.py': '0d73a0fc9eaf18d8'}
    w('- Harness: the three scripts were **untracked files** when the run started (the `harnessCommit` in `provenance.json` is the repository HEAD at that moment and does not contain them); they were committed unchanged afterwards. sha256 at the run: ' +
      ', '.join(f'`{k}` `{v}`' for k, v in at_run.items()) + '. The report script itself was written after the run. Current sha256 (after later edits): ' +
      ', '.join(f'`{k}` `{v[:16]}`' for k, v in scripts.items()) + '. Changes to `conformance-run.ts` since the run: `sameSet` sorts numerically (same result for port numbers 1 to 3); the capture start now waits until `tcpdump` reports it is listening on both taps (and refuses to send if it does not) instead of a fixed one-second sleep; UDP tags are unique within a run instead of wrapping at 500. The recorded captures were taken with the fixed wait, so those flows are only as reliable as that wait was; nothing in the recorded results changes. The later edits to the report script are the cross-reference text and closing its files.')
    w('- agentic-node-02 was not used (its Tailscale SSH timed out), so the legitimate-client role in the target topology is represented by node-01 here.')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    _write(OUT, '\n'.join(L).rstrip('\n') + '\n')
    print('wrote', OUT, len(L), 'lines')


if __name__ == '__main__':
    main()
