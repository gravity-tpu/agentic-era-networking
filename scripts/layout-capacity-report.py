#!/usr/bin/env python3
"""scripts/layout-capacity-report.py: turns a layout-capacity run directory into README.md and checks the pre-registered criteria.
Every number is read from results.json / provenance.json. Usage: python3 scripts/layout-capacity-report.py <run dir> <out README.md>
"""
import json, sys, statistics
from datetime import datetime
from zoneinfo import ZoneInfo

RUN, OUT = sys.argv[1], sys.argv[2]
def jload(p):
    with open(p) as fh: return json.load(fh)
res, prov = jload(f'{RUN}/results.json'), jload(f'{RUN}/provenance.json')
PRED, TOL = 4.24, 0.20

def stall_check(step):
    """A saturated step is a TRANSIENT STALL, not capacity, if at least half of its interior 1 s bins still delivered at the offered rate."""
    interior = step['binsPps'][2:-2]
    at_rate = sum(1 for b in interior if b >= 0.97 * step['sentPps'] * 0.987)
    return at_rate / len(interior) >= 0.5 if interior else False

rows = []
for r in res:
    sat = [s for s in r['steps'] if s.get('saturated')]
    cap = sat[0]['medianBusyDeliveredPps'] if sat else None
    stall = stall_check(sat[0]) if sat else False
    rows.append({'round': r['round'], 'k': r['k'], 'capacity': cap, 'stall': stall, 'satOffered': sat[0]['targetPps'] if sat else None,
                 'lastClean': max((s['targetPps'] for s in r['steps'] if not s.get('saturated') and 'ratio' in s), default=None)})
valid = [x for x in rows if x['capacity'] is not None and not x['stall']]

def ols(points):
    n = len(points); mx = sum(p[0] for p in points) / n; my = sum(p[1] for p in points) / n
    sxx = sum((p[0] - mx) ** 2 for p in points)
    slope = sum((p[0] - mx) * (p[1] - my) for p in points) / sxx
    return slope, my - slope * mx
def tus(c): return 1e6 / c
by_k = {}
for x in valid: by_k.setdefault(x['k'], []).append(x['capacity'])
mean_pts = [(k, tus(statistics.mean(v))) for k, v in sorted(by_k.items())]
slope, intercept = ols(mean_pts)
all_pts = [(x['k'], tus(x['capacity'])) for x in valid]
slope_all, _ = ols(all_pts)
slope_hi, _ = ols([(k, tus(max(v))) for k, v in sorted(by_k.items())])
slope_lo, _ = ols([(k, tus(min(v))) for k, v in sorted(by_k.items())])
lo, hi = PRED * (1 - TOL), PRED * (1 + TOL)
mono = all(statistics.mean(by_k[a]) > statistics.mean(by_k[b]) for a, b in zip(sorted(by_k), sorted(by_k)[1:]))
spread = {k: (max(v) - min(v)) / statistics.mean(v) for k, v in by_k.items() if len(v) > 1}
w = []; P = w.append
now = datetime.now(ZoneInfo('America/New_York')).strftime('%Y-%m-%d %H:%M ET')
P('# Hardware confirmation of the A4 versus A9 decision: results')
P('')
P(f'Generated by `scripts/layout-capacity-report.py` from `{RUN}` on {now}. The method, the prediction and what would count against the decision were fixed in [`PREREGISTRATION.md`](PREREGISTRATION.md) before the run. Run started {prov["startedEt"]}; bridge commit `{prov["bridgeCommit"][0]}` (branch `{prov["bridgeCommit"][1]}`, {prov["bridgeCommit"][2]} uncommitted files), `zodiac-bridge-server.js` sha256 `{prov["bridgeDistSha256"][:16]}`.')
P('')
P('## Capacity of the deployed policy with k quarantines above it (572-byte UDP, 600-byte IP packets)')
P('')
P('| k | Round | Capacity (pps) | Per-packet time (µs) | Saturated at offered | Last clean step | Note |')
P('| ---: | ---: | ---: | ---: | ---: | ---: | :--- |')
for x in rows:
    cap = x['capacity']
    note = 'not reached' if cap is None else ('**transient stall, excluded** (see below)' if x['stall'] else 'clean')
    P(f'| {x["k"]} | {x["round"]} | {cap if cap is not None else "-"} | {tus(cap):.1f} | {x["satOffered"]} | {x["lastClean"]} | {note} |' if cap else f'| {x["k"]} | {x["round"]} | - | - | - | {x["lastClean"]} | {note} |')
P('')
P('Capacity is the median of the 1 s delivered rates inside the first step whose delivered/sent ratio fell below 0.97. Delivered is read on the Jetson NIC on the Zodiac P3 link and corrected for the idle rate; a constant offset of about 1.3% (delivered/sent about 0.987 at every clean step) is the same measurement artifact recorded for the 2026-10-04 ladder.')
P('')
P('## The pre-registered check')
P('')
P('| Quantity | Value |')
P('| :--- | :--- |')
P(f'| Per-packet time by k (mean of valid rounds) | {", ".join(f"k={k}: {t:.1f} µs" for k, t in mean_pts)} |')
P(f'| **Slope, least squares on the per-k means** | **{slope:.2f} µs per quarantine** |')
P(f'| Slope using every valid round separately | {slope_all:.2f} µs |')
P(f'| Slope using the faster round at each k / the slower round | {slope_hi:.2f} / {slope_lo:.2f} µs |')
P(f'| Intercept (fixed cost with no quarantine) | {intercept:.1f} µs |')
P(f'| Predicted slope | {PRED} µs, accepted {lo:.1f} to {hi:.1f} µs |')
P(f'| Prediction 1 (slope in range) | **{"HOLDS" if lo <= slope <= hi else "DOES NOT HOLD"}**: the measured slope is {abs(slope / PRED - 1) * 100:.0f}% {"above" if slope > PRED else "below"} the prediction |')
P(f'| Prediction 2 (capacity falls monotonically with k) | {"holds" if mono else "DOES NOT HOLD"} |')
P(f'| Round-to-round spread at the same k (limit 10%) | {", ".join(f"k={k}: {v * 100:.1f}%" for k, v in sorted(spread.items()))} |')
P('')
stalled = [x for x in rows if x['stall']]
if stalled:
    P('## The excluded round')
    P('')
    for x in stalled:
        P(f'k={x["k"]}, round {x["round"]}: the ramp stopped at {x["satOffered"]} pps offered, but the per-second delivered rates inside that step were mostly at the offered rate with a stall of about two seconds in the middle (see `results.json`, step `binsPps`). A capacity limit would hold the delivered rate down for the whole step. The same k in round 2 saturated cleanly at {next((y["capacity"] for y in rows if y["k"] == x["k"] and y["round"] != x["round"] and y["capacity"]), "?")} pps. It resembles the unexplained stall recorded in the 2026-10-04 ladder at low load. The classification rule (a saturated step is a stall if at least half of its interior seconds delivered at the offered rate) was written after seeing this step and is stated here for that reason; the slope above does not depend on it for k=0, 4 and 8, which have two clean rounds each.')
    P('')
P('## What this says, and does not')
P('')
P('- The decision (A4 wins: quarantines above all forwarding rules) is **not contradicted** by the hardware: the measured capacities are monotonic in k and reproducible between rounds. But the **cost estimate in the decision record was too low**: see the slope and the prediction row above.')
P('- The fixed cost of the deployed policy is higher than the two-rule model, as expected (more rules scanned ahead of the matching one); this run does not separate that from the per-quarantine slope.')
P('- Not measured: the forwarding-first layout (the quarantine path cannot build it), a frame matched by a different rule than the tap-only rule, TCP, switch CPU, firmware other than 0.86. One switch.')
open(OUT, 'w').write('\n'.join(w) + '\n')
print(f'wrote {OUT}')
